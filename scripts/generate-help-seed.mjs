// Generates supabase/migrations/20260816_help_articles.sql from content/help/.
//
// WHY A GENERATOR RATHER THAN A HAND-WRITTEN MIGRATION
//
// The seed is 130-odd rows of prose across ten languages. Hand-maintaining
// that as SQL means every fix to a sentence is a hand-escaped string
// literal, and the first apostrophe someone forgets to double is a syntax
// error in a file nobody re-runs until the day they need it. The content
// lives as JSON, one file per language, and this turns it into SQL.
//
// It is the same arrangement as scripts/db-inventory.mjs -> db_missing_check.sql,
// including the drift test: scripts/tests/help-articles.test.mjs regenerates
// and compares, so a hand-edited migration cannot silently diverge from the
// content it claims to carry.
//
// Run: node scripts/generate-help-seed.mjs        (writes the migration)
//      node scripts/generate-help-seed.mjs --check (prints it, writes nothing)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const CONTENT = path.join(ROOT, "content", "help");
const OUT = path.join(ROOT, "supabase", "migrations", "20260816_help_articles.sql");

const manifest = JSON.parse(readFileSync(path.join(CONTENT, "manifest.json"), "utf8"));
const { categories, locales, baseLocale, articles: shape } = manifest;

/** SQL string literal. The only escaping a dollar-quoted-free seed needs. */
function lit(s) {
  return `'${String(s).replace(/'/g, "''")}'`;
}
/** text[] literal from a list of strings. */
function arr(list) {
  if (!list || list.length === 0) return "'{}'::text[]";
  return `array[${list.map(lit).join(", ")}]::text[]`;
}

// --- read every language file -------------------------------------------
const byLocale = new Map();
for (const loc of locales) {
  const file = path.join(CONTENT, `${loc}.json`);
  if (!existsSync(file)) {
    if (loc === baseLocale) throw new Error(`the base locale file is missing: ${file}`);
    byLocale.set(loc, {});
    continue;
  }
  const parsed = JSON.parse(readFileSync(file, "utf8"));
  if (parsed.locale !== loc) {
    throw new Error(`${loc}.json declares locale "${parsed.locale}"`);
  }
  byLocale.set(loc, parsed.articles ?? {});
}

// --- validate before emitting a single line of SQL -----------------------
// A generator that emits a broken seed and lets the database reject it has
// moved the error to the worst possible place: someone else's psql session.
const errors = [];
const slugs = shape.map((a) => a.slug);
const slugSet = new Set(slugs);
if (slugSet.size !== slugs.length) errors.push("manifest has duplicate slugs");

for (const a of shape) {
  if (!categories.includes(a.category)) {
    errors.push(`${a.slug}: category "${a.category}" is not in the manifest's category list`);
  }
}

const base = byLocale.get(baseLocale);
for (const slug of slugs) {
  if (!base[slug]) errors.push(`${baseLocale}.json is missing "${slug}" — the base locale must be complete`);
}
for (const slug of Object.keys(base)) {
  if (!slugSet.has(slug)) errors.push(`${baseLocale}.json has "${slug}", which the manifest does not list`);
}

for (const [loc, arts] of byLocale) {
  for (const [slug, art] of Object.entries(arts)) {
    if (!slugSet.has(slug)) {
      errors.push(`${loc}.json has "${slug}", which the manifest does not list`);
      continue;
    }
    for (const field of ["title", "body"]) {
      if (typeof art[field] !== "string" || !art[field].trim()) {
        errors.push(`${loc}/${slug}: ${field} is empty`);
      }
    }
    if (!Array.isArray(art.triggers) || art.triggers.length === 0) {
      errors.push(`${loc}/${slug}: no triggers`);
    }
    // RULE 1, at generation time as well as in the test: no number that can
    // go stale may reach the database. A price in an article is a quote.
    for (const field of ["title", "body"]) {
      const digits = String(art[field] ?? "").match(/\d/g);
      if (digits) errors.push(`${loc}/${slug}: ${field} contains a digit (${digits.join("")})`);
    }
  }
}

if (errors.length) {
  console.error("REFUSING TO GENERATE — fix the content first:\n");
  for (const e of errors) console.error(`  ${e}`);
  process.exit(1);
}

// --- rows ----------------------------------------------------------------
const rows = [];
for (const a of shape) {
  for (const loc of locales) {
    const art = byLocale.get(loc)?.[a.slug];
    if (!art) continue;
    rows.push({
      slug: a.slug,
      locale: loc,
      title: art.title,
      body: art.body,
      category: a.category,
      order: a.order,
      triggers: art.triggers,
    });
  }
}

const counts = locales.map((l) => `${l}=${rows.filter((r) => r.locale === l).length}`).join("  ");

const header = `-- The Help Centre, in ten languages.
--
-- GENERATED by scripts/generate-help-seed.mjs from content/help/.
-- Do not edit this file by hand: scripts/tests/help-articles.test.mjs
-- regenerates it and compares, so a hand edit fails the build. Edit the
-- JSON and re-run the generator.
--
-- IDEMPOTENT. Every statement is guarded. No DROP TABLE, no TRUNCATE, no
-- unqualified DELETE, no DROP CONSTRAINT, no DROP POLICY.
--
-- ============================================================================
-- WHAT WAS WRONG
-- ============================================================================
-- Twenty-seven help articles lived as Greek string literals in
-- src/lib/support/knowledge-base.ts and were served to all ten locales. A
-- Japanese reader opening /help got Greek. The same array fed the support
-- chat's canned answers, so the same reader could also be handed a Greek
-- paragraph in place of an answer.
--
-- ============================================================================
-- THE SHAPE
-- ============================================================================
-- One row per (slug, locale). English is the BASE: every article exists in
-- English, and a reader whose language is missing an article is shown the
-- English one with a visible marker saying so.
--
-- The fallback is structural, not a filter someone can forget: the loader
-- selects locale IN (requested, 'en') and never widens that set, so Greek
-- cannot reach a non-Greek reader by any code path. Greek is one more
-- translation here, with no privileges.
--
-- ROWS: ${rows.length} total across ${locales.length} locales
--   ${counts}
--
-- ============================================================================
-- ONE COLUMN BEYOND THE AGREED SHAPE, AND WHY
-- ============================================================================
-- \`triggers text[]\` is not in the column list this table was specified
-- with. It is here because the table also feeds the support chat's canned
-- answers, and matching "how do i cancel" to an article needs the phrases
-- people type — per language, since a French reader does not type Greek.
-- Keeping those in TypeScript would put half the content back in the code
-- this migration exists to empty. Everything else matches the agreed shape.
--
-- \`href\` is deliberately NOT here. A route is code, not content: it is the
-- same in every language, storing it once per row invites ${rows.length} chances to
-- drift, and scripts/tests/help-links.test.mjs can only prove a route
-- exists if it can see it in the repo. It lives in
-- src/lib/support/help-links.ts.
`;

const schema = `
-- 1. The table -------------------------------------------------------------
create table if not exists public.help_articles (
  id uuid primary key default gen_random_uuid(),
  slug text not null,
  locale text not null,
  title text not null,
  body text not null,
  category text not null,
  "order" integer not null default 0,
  published boolean not null default true,
  -- Phrases a reader types, in THIS locale. See the note above.
  triggers text[] not null default '{}'::text[],
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Columns added separately as well, so the file repairs a table that was
-- created by an earlier version of it rather than failing on the insert.
alter table public.help_articles add column if not exists triggers text[] not null default '{}'::text[];
alter table public.help_articles add column if not exists published boolean not null default true;
alter table public.help_articles add column if not exists "order" integer not null default 0;
alter table public.help_articles add column if not exists created_at timestamptz not null default now();
alter table public.help_articles add column if not exists updated_at timestamptz not null default now();

-- 2. The identity of a translation ------------------------------------------
-- (slug, locale) is what makes the French "cancel" a translation of the
-- English "cancel" rather than a second, unrelated article. It is also what
-- the seed's ON CONFLICT targets, so without it the seed is not idempotent.
create unique index if not exists help_articles_slug_locale_uidx
  on public.help_articles (slug, locale);

-- The read path: everything published in one language, in display order.
create index if not exists help_articles_locale_published_idx
  on public.help_articles (locale, published, category, "order");

-- 3. Constraints -------------------------------------------------------------
-- The database refuses a locale or a category the application does not
-- know. A TypeScript union stops a developer; this stops a SQL console, a
-- backfill, and a future admin screen.
do $locale_check$
begin
  if not exists (
    select 1 from pg_constraint
     where conname = 'help_articles_locale_check'
       and conrelid = 'public.help_articles'::regclass
  ) then
    alter table public.help_articles
      add constraint help_articles_locale_check
      check (locale in (${locales.map(lit).join(", ")}));
  end if;
end
$locale_check$;

do $category_check$
begin
  if not exists (
    select 1 from pg_constraint
     where conname = 'help_articles_category_check'
       and conrelid = 'public.help_articles'::regclass
  ) then
    alter table public.help_articles
      add constraint help_articles_category_check
      check (category in (${categories.map(lit).join(", ")}));
  end if;
end
$category_check$;

-- 4. updated_at ---------------------------------------------------------------
create or replace function public.help_articles_touch_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

do $touch_trigger$
begin
  if not exists (
    select 1 from pg_trigger
     where tgname = 'help_articles_touch_updated_at_trg'
       and tgrelid = 'public.help_articles'::regclass
  ) then
    create trigger help_articles_touch_updated_at_trg
      before update on public.help_articles
      for each row execute function public.help_articles_touch_updated_at();
  end if;
end
$touch_trigger$;

-- 5. RLS ----------------------------------------------------------------------
-- Public read of PUBLISHED rows: half of these answers — what does it cost,
-- what are credits, is my data safe — are asked before anyone has an
-- account, and an answer you must sign up to read is not an answer.
--
-- Writes: there is no insert, update or delete policy, on purpose. With RLS
-- enabled and no write policy, every anon and authenticated write is
-- refused by the database; the service role bypasses RLS and is the only
-- way content changes. That is "service-role write" expressed as the
-- absence of a hole rather than as a rule someone has to get right.
alter table public.help_articles enable row level security;

do $read_policy$
begin
  if not exists (
    select 1 from pg_policies
     where schemaname = 'public'
       and tablename = 'help_articles'
       and policyname = 'help_articles_public_read_published'
  ) then
    create policy "help_articles_public_read_published"
      on public.help_articles
      for select
      using (published = true);
  end if;
end
$read_policy$;

grant select on public.help_articles to anon, authenticated;
`;

const seedHeader = `
-- 6. The content ---------------------------------------------------------------
-- ON CONFLICT DO UPDATE: this migration is the source of the shipped copy,
-- so re-running it restores that copy. To change an article, edit
-- content/help/<locale>.json and regenerate — do not edit rows by hand, or
-- the next run of this file will quietly undo you.
--
-- created_at is NOT in the update list: a re-run must not rewrite when a
-- row first appeared.
insert into public.help_articles (slug, locale, title, body, category, "order", triggers, published)
values`;

const values = rows
  .map(
    (r) =>
      `  (${lit(r.slug)}, ${lit(r.locale)}, ${lit(r.title)}, ${lit(r.body)}, ${lit(r.category)}, ${r.order}, ${arr(
        r.triggers
      )}, true)`
  )
  .join(",\n");

const seedTail = `
on conflict (slug, locale) do update
  set title      = excluded.title,
      body       = excluded.body,
      category   = excluded.category,
      "order"    = excluded."order",
      triggers   = excluded.triggers,
      published  = excluded.published,
      updated_at = now();

-- 7. What landed -----------------------------------------------------------------
-- Run this after the migration. It should return one row per locale, and
-- the English count must be the largest — English is the base, and a locale
-- with MORE articles than English means a slug exists that nothing falls
-- back to.
--
-- select locale, count(*) as articles
--   from public.help_articles
--  where published
--  group by locale
--  order by count(*) desc, locale;
`;

const sql = `${header}${schema}${seedHeader}\n${values}\n${seedTail}`;

if (process.argv.includes("--check")) {
  process.stdout.write(sql);
} else {
  writeFileSync(OUT, sql, "utf8");
  console.error(`wrote ${path.relative(ROOT, OUT)} — ${rows.length} rows (${counts})`);
}
