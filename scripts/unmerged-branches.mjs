#!/usr/bin/env node
/*
 * WHAT IS ON A BRANCH AND NOWHERE ELSE.
 *
 * Eighty-nine commits across eight branches sat unmerged for weeks, and
 * nobody knew — including two branches carrying whole user-facing pages
 * (acceptable-use, ai-transparency, changelog, collaboration, contact)
 * that exist on main in no form at all. They were not rejected. They were
 * forgotten, which is a different problem and needs a different fix: not
 * a better decision, just something that says the branches are there.
 *
 * WHY COMMIT COUNTS ARE NOT THE MEASURE. A branch can be twenty commits
 * ahead and carry nothing — main reached the same place another way, and
 * the commits are only a different route to code that already shipped.
 * The first pass of this triage said exactly that about all seven
 * branches, by grepping for feature words, and it was WRONG: "changelog"
 * matched a comment. A word is not a feature.
 *
 * SO IT COUNTS FILES THAT EXIST ON THE BRANCH AND NOT ON MAIN. That is
 * the one signal that cannot be produced by main having moved on: a path
 * main has never had is work main has never had. It over-reports renames
 * (lib/admin.ts became lib/supabase/admin.ts, and three branches still
 * show the old path) and it under-reports a modified file, so both limits
 * are printed rather than hidden.
 *
 * Run: node scripts/unmerged-branches.mjs [--write] [--json]
 *      --write  updates docs/unmerged-branches.md
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const git = (...a) => execFileSync("git", a, { encoding: "utf8", maxBuffer: 64e6 }).trim();
const MAIN = "origin/main";

function branches() {
  return git("for-each-ref", "--format=%(refname:short)", "refs/remotes/origin")
    .split("\n")
    .map((s) => s.trim())
    .filter((b) => b && b !== MAIN && !b.endsWith("/HEAD"));
}

const rows = [];
for (const b of branches()) {
  let ahead;
  try { ahead = Number(git("rev-list", "--count", `${MAIN}..${b}`)); } catch { continue; }
  if (ahead === 0) continue;
  const mainFiles = new Set(git("ls-tree", "-r", "--name-only", MAIN, "--", "src").split("\n"));
  const theirs = git("ls-tree", "-r", "--name-only", b, "--", "src").split("\n").filter(Boolean);
  const only = theirs.filter((f) => !mainFiles.has(f));
  // Routes and pages are the ones a person can miss from the outside.
  const routes = only.filter((f) => f.startsWith("src/app/"));
  rows.push({
    branch: b.replace(/^origin\//, ""),
    ahead,
    onlyFiles: only.length,
    routes: routes.length,
    lastCommit: git("log", "-1", "--format=%ad", "--date=short", b),
    subject: git("log", "-1", "--format=%s", b).slice(0, 60),
    examples: routes.slice(0, 4),
  });
}
rows.sort((a, b) => b.routes - a.routes || b.onlyFiles - a.onlyFiles);

if (process.argv.includes("--json")) {
  console.log(JSON.stringify(rows, null, 2));
  process.exit(0);
}

const carrying = rows.filter((r) => r.onlyFiles > 0);
const lines = [];
lines.push("# Branches carrying work that is not on main");
lines.push("");
lines.push(`Generated by \`node scripts/unmerged-branches.mjs --write\`. ${rows.length} branch(es) ahead of main; ${carrying.length} carry at least one file main has never had.`);
lines.push("");
lines.push("A file main has never had is work main has never had — the one signal that cannot come from main simply moving on. It OVER-reports renames (a path that moved shows as branch-only) and UNDER-reports edits to files main already has, so read it as \"look here\", not as a verdict.");
lines.push("");
lines.push("| branch | commits | files only here | routes/pages | last commit | newest subject |");
lines.push("|---|---|---|---|---|---|");
for (const r of rows) {
  lines.push(`| \`${r.branch}\` | ${r.ahead} | ${r.onlyFiles} | ${r.routes} | ${r.lastCommit} | ${r.subject} |`);
}
const withRoutes = rows.filter((r) => r.routes > 0);
if (withRoutes.length) {
  lines.push("");
  lines.push("## Routes and pages that exist on no other branch and not on main");
  for (const r of withRoutes) {
    lines.push("");
    lines.push(`**\`${r.branch}\`** — ${r.routes} route/page file(s):`);
    for (const e of r.examples) lines.push(`- \`${e}\``);
    if (r.routes > r.examples.length) lines.push(`- …and ${r.routes - r.examples.length} more`);
  }
}
const out = lines.join("\n") + "\n";

if (process.argv.includes("--write")) {
  writeFileSync("docs/unmerged-branches.md", out);
  console.log(`docs/unmerged-branches.md updated — ${rows.length} branch(es) ahead, ${carrying.length} carrying unique files`);
} else {
  console.log(out);
}
// Non-zero when a branch carries a ROUTE main has never had: that is the
// shape of forgotten work a person can see in the product.
process.exit(withRoutes.length > 0 ? 1 : 0);
